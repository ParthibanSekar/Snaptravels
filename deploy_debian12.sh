#!/bin/bash
# ============================================================
#  SnapTravels — Debian 12 (Bookworm) Fresh-Machine Installer
#
#  Run ONCE on a brand-new Debian 12 server as root or with sudo.
#
#  Usage:
#    bash deploy_debian12.sh            → full install + start
#    bash deploy_debian12.sh --nginx    → also configure Nginx reverse proxy
#    bash deploy_debian12.sh --systemd  → install as a systemd service
#    bash deploy_debian12.sh --nginx --systemd → both
#
#  After this script finishes, manage the app with:
#    bash snaptravels.sh start | stop | restart | status | logs
#    (or systemctl start|stop|restart snaptravels if --systemd was used)
# ============================================================

set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")" && pwd)"
NGINX_MODE=false
SYSTEMD_MODE=false
for arg in "$@"; do
    case "$arg" in
        --nginx)   NGINX_MODE=true  ;;
        --systemd) SYSTEMD_MODE=true ;;
    esac
done

# ── Colours ─────────────────────────────────────────────────
GREEN='\033[0;32m'; YELLOW='\033[1;33m'
RED='\033[0;31m';   CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error()   { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

# ── 0. Must be root (or sudo) ────────────────────────────────
if [[ $EUID -ne 0 ]]; then
    error "Please run as root:  sudo bash deploy_debian12.sh"
fi

echo ""
echo -e "${BOLD}╔══════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}║   SnapTravels — Debian 12 Installer          ║${NC}"
echo -e "${BOLD}╚══════════════════════════════════════════════╝${NC}"
echo ""

# ── 1. System packages ───────────────────────────────────────
info "Updating package lists..."
apt-get update -qq

info "Installing system dependencies..."
apt-get install -y -qq \
    python3 \
    python3-venv \
    python3-dev \
    python3-pip \
    pkg-config \
    lsof \
    curl \
    git \
    build-essential \
    libffi-dev \
    libssl-dev \
    libpq-dev \
    libjpeg-dev \
    zlib1g-dev \
    libwebp-dev \
    libfreetype6-dev \
    liblcms2-dev \
    libopenjp2-7-dev \
    libtiff-dev \
    sqlite3 \
    libsqlite3-dev \
    logrotate

# Confirm Python version (Debian 12 ships 3.11)
PYVER=$(python3 --version 2>&1)
success "Python: $PYVER"

# ── 2. Nginx (optional, --nginx flag) ───────────────────────
if $NGINX_MODE; then
    info "Installing Nginx..."
    apt-get install -y -qq nginx
    success "Nginx installed."
fi

# ── 3. Fix permissions on app directory ─────────────────────
info "Setting permissions on $APP_DIR ..."
chmod -R 755 "$APP_DIR"
chmod +x "$APP_DIR/snaptravels.sh"

# ── 3a. Remove stale venv from dev machine (wrong Python paths) ──
for STALE_VENV in "$APP_DIR/venv" "$APP_DIR/venv_new"; do
    if [ -d "$STALE_VENV" ]; then
        # Remove if python binary is missing or points to a macOS/Windows path
        if [ ! -x "$STALE_VENV/bin/python" ]; then
            warn "Removing stale/broken venv: $STALE_VENV"
            rm -rf "$STALE_VENV"
        elif head -1 "$STALE_VENV/bin/pip" 2>/dev/null | grep -q "Users/\|C:\\\\"; then
            warn "Removing dev-machine venv (wrong Python path): $STALE_VENV"
            rm -rf "$STALE_VENV"
        fi
    fi
done

# ── 4. Create required directories ──────────────────────────
info "Creating required directories..."
mkdir -p "$APP_DIR/logs"
mkdir -p "$APP_DIR/instance"
success "Directories: logs/, instance/ ready."

# ── 5. Create .env if it doesn't exist ──────────────────────
ENV_FILE="$APP_DIR/.env"
if [ ! -f "$ENV_FILE" ]; then
    info "Creating default .env file..."
    SECRET=$(python3 -c "import secrets; print(secrets.token_hex(32))")
    cat > "$ENV_FILE" <<EOF
# SnapTravels environment configuration
# Generated by deploy_debian12.sh on $(date)

APP_ENV=production
FLASK_ENV=production
APP_NAME=SnapTravels
SECRET_KEY=${SECRET}
PORT=8080

# Auto Chaos Engine — set to 1 to enable the background scheduler
# (required for Auto Chaos Mode to fire events automatically)
CHAOS_SCHEDULER_ENABLED=1

# Site24x7 Observability (optional)
SITE24X7_RUM_APP_KEY=
S247_LICENSE_KEY=

# Set to 1 to enable structured JSON log output (for APM log ingestion)
SNAPTRAVELS_JSON_LOGS=0

# Mail settings (optional — leave blank to disable email sending)
MAIL_SERVER=
MAIL_PORT=587
MAIL_USERNAME=
MAIL_PASSWORD=
MAIL_DEFAULT_SENDER=

# Encryption key for TOTP secrets (leave blank to auto-generate on first run)
TOTP_ENCRYPTION_KEY=
EOF
    success ".env file created at $ENV_FILE"
else
    success "Existing .env found — skipping."
fi

# Source .env so PORT is available for this script
set -a
source "$ENV_FILE" 2>/dev/null || true
set +a
PORT=${PORT:-8080}

# ── 6. Create Python venv + install dependencies ────────────
info "Setting up Python virtual environment..."
VENV="$APP_DIR/venv"
if [ ! -d "$VENV" ]; then
    python3 -m venv "$VENV"
    success "Virtual environment created at $VENV"
fi

info "Installing Python dependencies from requirements.txt..."
"$VENV/bin/pip" install --upgrade pip -q
"$VENV/bin/pip" install -r "$APP_DIR/requirements.txt" -q
success "All Python dependencies installed."

# Quick sanity check — import the critical packages
info "Verifying critical packages..."
"$VENV/bin/python" -c "
import flask, flask_sqlalchemy, flask_wtf, flask_limiter, flask_mail
import pyotp, qrcode, cryptography, apscheduler, bleach, PIL, jwt
import email_validator, flasgger, gunicorn
print('  All critical packages verified.')
" || {
    error "Some Python packages failed to import. Check requirements.txt and try again."
}
success "Package verification passed."

# ── 7. Initialise database ──────────────────────────────────
info "Initialising database..."
cd "$APP_DIR"
"$VENV/bin/python" -c "
import sys, os
sys.path.insert(0, os.getcwd())
from app import create_app, db
app = create_app()
with app.app_context():
    db.create_all()
    print('  Database tables created/verified.')
"

# Run seeders if the Flask CLI commands are available
"$VENV/bin/python" -m flask --app main seed-all 2>/dev/null || true
"$VENV/bin/python" -m flask --app main seed-transport 2>/dev/null || true

# Seed blog posts
"$VENV/bin/python" -c "
import sys, os; sys.path.insert(0, os.getcwd())
from app import create_app, db
app = create_app()
with app.app_context():
    try:
        from app.services.seeder import seed_blog
        seed_blog()
    except Exception:
        pass
" 2>/dev/null || true

# Sync images to Flask static folder
if [ -d "$APP_DIR/static/images" ] && [ ! -f "$APP_DIR/app/static/images/.synced" ]; then
    info "Syncing images to app/static/images..."
    mkdir -p "$APP_DIR/app/static/images"
    cp -rn "$APP_DIR/static/images/." "$APP_DIR/app/static/images/" 2>/dev/null || true
    touch "$APP_DIR/app/static/images/.synced"
fi

# Patch image paths
if [ -f "$APP_DIR/patch_images.py" ]; then
    "$VENV/bin/python" "$APP_DIR/patch_images.py" 2>/dev/null || true
fi

success "Database ready."

# ── 8. Log rotation (logrotate) ─────────────────────────────
info "Configuring log rotation..."
cat > "/etc/logrotate.d/snaptravels" <<LREOF
# SnapTravels — log rotation
# Application logs (Flask + Gunicorn)

${APP_DIR}/logs/app.log
${APP_DIR}/logs/error.log
${APP_DIR}/logs/access.log
{
    daily
    missingok
    rotate 30
    compress
    delaycompress
    notifempty
    copytruncate
    dateext
    dateformat -%Y%m%d
    su root root
    maxsize 100M
}
LREOF
success "Log rotation configured (daily, 30 days retention, 100 MB max per file)."

# ── 9. Systemd service (optional, --systemd flag) ───────────
if $SYSTEMD_MODE; then
    SERVICE_NAME="snaptravels"
    info "Creating systemd service: ${SERVICE_NAME}.service"

    cat > "/etc/systemd/system/${SERVICE_NAME}.service" <<SVCEOF
[Unit]
Description=SnapTravels Flask Application
After=network.target

[Service]
Type=simple
User=root
Group=root
WorkingDirectory=${APP_DIR}
EnvironmentFile=${ENV_FILE}
ExecStart=${VENV}/bin/gunicorn \\
    --bind 0.0.0.0:${PORT} \\
    --workers 4 \\
    --timeout 120 \\
    --access-logfile ${APP_DIR}/logs/access.log \\
    --error-logfile ${APP_DIR}/logs/error.log \\
    --capture-output \\
    wsgi:app
ExecReload=/bin/kill -s HUP \$MAINPID
Restart=on-failure
RestartSec=5
KillMode=mixed
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
SVCEOF

    systemctl daemon-reload
    systemctl enable "$SERVICE_NAME"
    systemctl restart "$SERVICE_NAME"
    success "Systemd service '${SERVICE_NAME}' created, enabled, and started (Gunicorn, 4 workers on port ${PORT})."
else
    # ── Launch via snaptravels.sh (dev/simple mode) ──────────
    echo ""
    info "Handing off to snaptravels.sh start ..."
    echo ""
    bash "$APP_DIR/snaptravels.sh" start
fi

# ── 10. Optional: Nginx reverse proxy config ────────────────
if $NGINX_MODE; then
    CONF="/etc/nginx/sites-available/snaptravels"

    info "Writing Nginx config → $CONF"
    cat > "$CONF" <<EOF
server {
    listen 80;
    server_name _;                  # Replace with your domain name

    # Increase upload / request size
    client_max_body_size 20M;

    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # Proxy to Flask/Gunicorn app
    location / {
        proxy_pass         http://127.0.0.1:${PORT};
        proxy_http_version 1.1;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
        proxy_connect_timeout 10s;
    }

    # Serve Flask static files directly via Nginx (faster)
    location /static/ {
        alias ${APP_DIR}/app/static/;
        expires 7d;
        add_header Cache-Control "public";
    }

    # Serve asset images directly via Nginx
    location /assets/ {
        alias ${APP_DIR}/assets/;
        expires 30d;
        add_header Cache-Control "public, immutable";
        access_log off;
    }

    # Health check endpoint (bypass access logging)
    location = /health {
        proxy_pass http://127.0.0.1:${PORT}/health;
        access_log off;
    }
}
EOF

    # Enable the site
    ln -sf "$CONF" /etc/nginx/sites-enabled/snaptravels
    rm -f /etc/nginx/sites-enabled/default

    nginx -t && systemctl reload nginx
    success "Nginx configured and reloaded."
    echo ""
    echo -e "  ${BOLD}Nginx is now proxying port 80 → Flask on port ${PORT}${NC}"
    echo -e "  To add HTTPS (free SSL), install certbot:"
    echo -e "    apt install certbot python3-certbot-nginx"
    echo -e "    certbot --nginx -d yourdomain.com"
fi

# ── 11. Done ─────────────────────────────────────────────────
echo ""
echo -e "${BOLD}${GREEN}╔══════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}${GREEN}║   Deployment complete!                       ║${NC}"
echo -e "${BOLD}${GREEN}╚══════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  ${BOLD}Manage the app:${NC}"
if $SYSTEMD_MODE; then
    echo "    systemctl start snaptravels"
    echo "    systemctl stop snaptravels"
    echo "    systemctl restart snaptravels"
    echo "    systemctl status snaptravels"
    echo "    journalctl -u snaptravels -f"
else
    echo "    bash snaptravels.sh start"
    echo "    bash snaptravels.sh stop"
    echo "    bash snaptravels.sh restart"
    echo "    bash snaptravels.sh logs"
    echo "    bash snaptravels.sh status"
fi
echo ""
echo -e "  ${BOLD}App logs:${NC}"
echo "    ${APP_DIR}/logs/app.log       (application events)"
echo "    ${APP_DIR}/logs/error.log     (errors only)"
echo "    ${APP_DIR}/logs/access.log    (HTTP requests, if Gunicorn)"
echo ""
echo -e "  ${BOLD}Default login credentials:${NC}"
echo "    Admin  →  admin@snaptravels.online  /  Admin@123"
echo "    User   →  parthiban@snaptravels.online  /  Test@123"
echo ""
