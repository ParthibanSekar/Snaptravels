#!/bin/bash
# ============================================================
#  SnapTravels — Full Production Deployment
#  Debian 12 + Gunicorn + Nginx + HTTPS + Site24x7 APM
#
#  Run as root:
#    sudo bash deploy_production.sh --domain snaptravels.yourdomain.com
#
#  This script:
#    1. Installs system packages (Python 3, Nginx, Certbot)
#    2. Creates venv + installs pip deps (including gunicorn & apminsight)
#    3. Creates a systemd service (gunicorn with 4 workers)
#    4. Configures Nginx reverse proxy + HTTPS via Let's Encrypt
#    5. Sets up the .env with Site24x7 keys (prompts if missing)
#    6. Installs & enables Site24x7 APM Data Exporter
# ============================================================

set -euo pipefail

# ── Parse flags ────────────────────────────────────────────
DOMAIN=""
SKIP_HTTPS=false
while [[ $# -gt 0 ]]; do
    case $1 in
        --domain)    DOMAIN="$2"; shift 2;;
        --no-https)  SKIP_HTTPS=true; shift;;
        *)           echo "Unknown arg: $1"; exit 1;;
    esac
done

APP_DIR="$(cd "$(dirname "$0")" && pwd)"
PORT=8000
WORKERS=4
USER_NAME="www-data"
SERVICE_NAME="snaptravels"
VENV="$APP_DIR/venv"

# ── Colours ────────────────────────────────────────────────
GREEN='\033[0;32m'; YELLOW='\033[1;33m'
RED='\033[0;31m'; CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
err()     { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

[[ $EUID -ne 0 ]] && err "Run as root: sudo bash deploy_production.sh --domain yourdomain.com"

echo ""
echo -e "${BOLD}╔═══════════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}║   SnapTravels — Production Deployment             ║${NC}"
echo -e "${BOLD}║   Gunicorn + Nginx + HTTPS + Site24x7             ║${NC}"
echo -e "${BOLD}╚═══════════════════════════════════════════════════╝${NC}"
echo ""

# ══════════════════════════════════════════════════════════════
#  1. System packages
# ══════════════════════════════════════════════════════════════
info "Installing system packages..."
apt-get update -qq
apt-get install -y -qq \
    python3 python3-venv python3-dev python3-pip \
    nginx certbot python3-certbot-nginx \
    lsof curl git build-essential \
    libffi-dev libssl-dev libpq-dev \
    libjpeg-dev zlib1g-dev libwebp-dev
success "System packages installed."

# ══════════════════════════════════════════════════════════════
#  2. Python venv + dependencies
# ══════════════════════════════════════════════════════════════
info "Setting up Python environment..."

# Remove stale venvs from dev machine
for STALE in "$APP_DIR/venv" "$APP_DIR/venv_new"; do
    if [ -d "$STALE" ]; then
        PYPATH=$(head -1 "$STALE/bin/python" 2>/dev/null || echo "")
        if [[ ! -x "$STALE/bin/python" ]] || [[ "$PYPATH" == *"Users/"* ]]; then
            warn "Removing stale venv: $STALE"
            rm -rf "$STALE"
        fi
    fi
done

if [ ! -d "$VENV" ]; then
    python3 -m venv "$VENV"
    success "Created venv at $VENV"
fi

"$VENV/bin/pip" install --upgrade pip -q
"$VENV/bin/pip" install -r "$APP_DIR/requirements.txt" -q
success "Python dependencies installed (gunicorn + apminsight included)."

# ══════════════════════════════════════════════════════════════
#  3. Environment file (.env)
# ══════════════════════════════════════════════════════════════
ENV_FILE="$APP_DIR/.env"
if [ ! -f "$ENV_FILE" ]; then
    info "Creating .env file..."
    SECRET=$(python3 -c "import secrets; print(secrets.token_hex(32))")
    cat > "$ENV_FILE" <<ENVEOF
# SnapTravels — Production Environment
# Generated by deploy_production.sh on $(date)

APP_ENV=production
APP_NAME=SnapTravels
SECRET_KEY=${SECRET}
PORT=${PORT}

# ── Site24x7 Observability ─────────────────────────────────
# RUM App Key  → Site24x7 console → Admin → RUM Application → App Key
SITE24X7_RUM_APP_KEY=

# APM License Key → Site24x7 console → Admin → Developer → Device Key
S247_LICENSE_KEY=

# ── Chaos Engineering ──────────────────────────────────────
CHAOS_SCHEDULER_ENABLED=1

# ── Email (optional) ──────────────────────────────────────
MAIL_SERVER=
MAIL_PORT=587
MAIL_USERNAME=
MAIL_PASSWORD=
MAIL_DEFAULT_SENDER=

# ── Encryption (leave blank to auto-generate) ─────────────
TOTP_ENCRYPTION_KEY=
ENVEOF
    success ".env created — edit it now to add your Site24x7 keys."
    echo ""
    echo -e "  ${YELLOW}ACTION REQUIRED:${NC} Edit ${BOLD}$ENV_FILE${NC} and fill in:"
    echo "    SITE24X7_RUM_APP_KEY=<your RUM app key>"
    echo "    S247_LICENSE_KEY=<your APM license key>"
    echo ""
    read -rp "  Press ENTER after you've edited .env (or press ENTER to continue and edit later)... "
else
    success "Existing .env found."
fi

# Source .env for this script
set -a
source "$ENV_FILE" 2>/dev/null || true
set +a

# ══════════════════════════════════════════════════════════════
#  4. Initialise database
# ══════════════════════════════════════════════════════════════
info "Initialising database..."
cd "$APP_DIR"
"$VENV/bin/python" -c "
from app import create_app, db
app = create_app()
with app.app_context():
    db.create_all()
    print('  Database tables created/verified.')
"

# Run seeders if they exist
if [ -f "$APP_DIR/init_db.py" ]; then
    "$VENV/bin/python" "$APP_DIR/init_db.py" 2>/dev/null || true
fi
success "Database ready."

# ══════════════════════════════════════════════════════════════
#  5. Gunicorn systemd service
# ══════════════════════════════════════════════════════════════
info "Creating systemd service..."

cat > "/etc/systemd/system/${SERVICE_NAME}.service" <<SVCEOF
[Unit]
Description=SnapTravels (Gunicorn)
After=network.target

[Service]
Type=notify
User=root
Group=root
WorkingDirectory=${APP_DIR}
EnvironmentFile=${ENV_FILE}
ExecStart=${VENV}/bin/gunicorn \\
    --bind 127.0.0.1:${PORT} \\
    --workers ${WORKERS} \\
    --timeout 120 \\
    --access-logfile ${APP_DIR}/logs/access.log \\
    --error-logfile ${APP_DIR}/logs/error.log \\
    --capture-output \\
    wsgi:app
ExecReload=/bin/kill -s HUP \$MAINPID
Restart=on-failure
RestartSec=5
KillMode=mixed
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
SVCEOF

mkdir -p "$APP_DIR/logs"
systemctl daemon-reload
systemctl enable "$SERVICE_NAME"
systemctl restart "$SERVICE_NAME"
success "Gunicorn service started (${WORKERS} workers on 127.0.0.1:${PORT})."

# ══════════════════════════════════════════════════════════════
#  6. Nginx reverse proxy
# ══════════════════════════════════════════════════════════════
SERVER_NAME="${DOMAIN:-_}"
CONF="/etc/nginx/sites-available/${SERVICE_NAME}"

info "Writing Nginx config → $CONF"
cat > "$CONF" <<NGXEOF
# SnapTravels — Nginx reverse proxy
# Generated by deploy_production.sh

server {
    listen 80;
    server_name ${SERVER_NAME};

    client_max_body_size 20M;

    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # Serve static files directly (bypass Gunicorn)
    location /static/ {
        alias ${APP_DIR}/app/static/;
        expires 30d;
        add_header Cache-Control "public, immutable";
        access_log off;
    }

    # Proxy everything else to Gunicorn
    location / {
        proxy_pass         http://127.0.0.1:${PORT};
        proxy_http_version 1.1;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
        proxy_connect_timeout 10s;
    }

    # Health check (bypass logging)
    location = /health {
        proxy_pass http://127.0.0.1:${PORT}/health;
        access_log off;
    }
}
NGXEOF

ln -sf "$CONF" "/etc/nginx/sites-enabled/${SERVICE_NAME}"
rm -f /etc/nginx/sites-enabled/default

nginx -t && systemctl reload nginx
success "Nginx configured — proxying :80 → Gunicorn :${PORT}."

# ══════════════════════════════════════════════════════════════
#  7. HTTPS via Certbot (Let's Encrypt)
# ══════════════════════════════════════════════════════════════
if [[ -n "$DOMAIN" ]] && [[ "$SKIP_HTTPS" == false ]]; then
    info "Requesting HTTPS certificate for $DOMAIN ..."
    certbot --nginx -d "$DOMAIN" --non-interactive --agree-tos \
        --email "admin@${DOMAIN}" --redirect 2>&1 || {
        warn "Certbot failed — you can retry manually:"
        echo "  certbot --nginx -d $DOMAIN"
    }
    success "HTTPS enabled for $DOMAIN."
elif [[ -n "$DOMAIN" ]]; then
    echo ""
    echo -e "  ${YELLOW}HTTPS skipped (--no-https).${NC} Enable later with:"
    echo "    certbot --nginx -d $DOMAIN"
else
    echo ""
    warn "No --domain given. Nginx is listening on port 80 for any hostname."
    echo "  To add a domain + HTTPS later:"
    echo "    1. Edit /etc/nginx/sites-available/${SERVICE_NAME} → set server_name"
    echo "    2. certbot --nginx -d yourdomain.com"
fi

# ══════════════════════════════════════════════════════════════
#  8. Site24x7 APM Data Exporter (required for Python agent)
# ══════════════════════════════════════════════════════════════
echo ""
info "Checking Site24x7 APM Data Exporter..."
if command -v s247DataExporter &>/dev/null || [ -f /opt/site24x7/apminsight/bin/s247DataExporter ]; then
    success "Data Exporter already installed."
else
    echo ""
    echo -e "  ${YELLOW}The Site24x7 Python APM agent requires the Data Exporter service.${NC}"
    echo ""
    echo "  Install it by running:"
    echo "    bash -c \"\$(curl -sL https://staticdownloads.site24x7.in/apminsight/S247DataExporter/linux/InstallDataExporter.sh)\" -- -key <YOUR_S247_LICENSE_KEY>"
    echo ""
    echo "  Or download manually from:"
    echo "    https://www.site24x7.com/help/apm/python-agent/install-python-agent.html"
    echo ""

    if [[ -n "${S247_LICENSE_KEY:-}" ]]; then
        read -rp "  Install the Data Exporter now? [y/N] " INSTALL_DE
        if [[ "$INSTALL_DE" =~ ^[Yy]$ ]]; then
            info "Installing Site24x7 Data Exporter..."
            curl -sL https://staticdownloads.site24x7.in/apminsight/S247DataExporter/linux/InstallDataExporter.sh | bash -s -- -key "$S247_LICENSE_KEY" || {
                warn "Data Exporter install failed — install it manually later."
            }
        fi
    fi
fi

# ══════════════════════════════════════════════════════════════
#  9. Log rotation (logrotate)
# ══════════════════════════════════════════════════════════════
info "Configuring log rotation..."
cat > "/etc/logrotate.d/${SERVICE_NAME}" <<LREOF
# SnapTravels — log rotation
# Gunicorn access & error logs + Flask application logs

${APP_DIR}/logs/access.log
${APP_DIR}/logs/error.log
${APP_DIR}/logs/app.log
{
    daily
    missingok
    rotate 30
    compress
    delaycompress
    notifempty
    copytruncate
    dateext
    dateformat -%Y%m%d
    su root root
}
LREOF
success "Log rotation configured (daily, 30 days retention, compressed)."

# ══════════════════════════════════════════════════════════════
#  10. Summary
# ══════════════════════════════════════════════════════════════
echo ""
echo -e "${BOLD}${GREEN}╔═══════════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}${GREEN}║   Deployment Complete!                             ║${NC}"
echo -e "${BOLD}${GREEN}╚═══════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  ${BOLD}Service:${NC}      systemctl {start|stop|restart|status} ${SERVICE_NAME}"
echo -e "  ${BOLD}Logs:${NC}         journalctl -u ${SERVICE_NAME} -f"
echo -e "              ${APP_DIR}/logs/app.log       (application events)"
echo -e "              ${APP_DIR}/logs/access.log    (HTTP requests)"
echo -e "              ${APP_DIR}/logs/error.log     (Gunicorn errors)"
echo ""
if [[ -n "$DOMAIN" ]]; then
    echo -e "  ${BOLD}URL:${NC}          https://${DOMAIN}"
else
    IP=$(curl -s4 ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')
    echo -e "  ${BOLD}URL:${NC}          http://${IP}"
fi
echo ""
echo -e "  ${BOLD}Login:${NC}        admin@snaptravels.online / Admin@123"
echo -e "              parthiban@snaptravels.online / Test@123"
echo ""
echo -e "  ${BOLD}Site24x7:${NC}"
echo "    RUM       → Set SITE24X7_RUM_APP_KEY in .env, then restart"
echo "    APM       → Set S247_LICENSE_KEY in .env + install Data Exporter"
echo "    Synthetic → See DEPLOYMENT_GUIDE.md for monitor config"
echo ""
echo -e "  ${BOLD}Manage:${NC}"
echo "    systemctl restart ${SERVICE_NAME}     # restart Gunicorn"
echo "    systemctl reload nginx               # reload Nginx config"
echo "    certbot renew --dry-run              # test cert renewal"
echo ""
