#!/bin/bash
# ============================================================
#  SnapTravels — Nginx Setup Script
#  Sets up Nginx as a reverse proxy for the Flask app.
#
#  Usage:
#    bash setup_nginx.sh                    # Default: Nginx :8080 → Flask :5000
#    bash setup_nginx.sh --nginx-port 80    # Nginx :80 → Flask :5000
#    bash setup_nginx.sh --flask-port 3000  # Nginx :8080 → Flask :3000
#    bash setup_nginx.sh --domain snaptravels.online
# ============================================================

set -euo pipefail

# ── Defaults ──────────────────────────────────────────────
NGINX_PORT=8080
FLASK_PORT=5000
DOMAIN="_"
APP_DIR="$(cd "$(dirname "$0")" && pwd)"
SERVICE_NAME="snaptravels"

# ── Parse flags ───────────────────────────────────────────
while [[ $# -gt 0 ]]; do
    case $1 in
        --nginx-port)  NGINX_PORT="$2"; shift 2;;
        --flask-port)  FLASK_PORT="$2"; shift 2;;
        --domain)      DOMAIN="$2"; shift 2;;
        *)             echo "Unknown arg: $1"; exit 1;;
    esac
done

# ── Colours ───────────────────────────────────────────────
GREEN='\033[0;32m'; YELLOW='\033[1;33m'
RED='\033[0;31m'; CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
err()     { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

echo ""
echo -e "${BOLD}╔═══════════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}║   SnapTravels — Nginx Setup                       ║${NC}"
echo -e "${BOLD}╚═══════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  Nginx port  : ${BOLD}$NGINX_PORT${NC}"
echo -e "  Flask port  : ${BOLD}$FLASK_PORT${NC}"
echo -e "  Domain      : ${BOLD}$DOMAIN${NC}"
echo -e "  App dir     : ${BOLD}$APP_DIR${NC}"
echo ""

# ══════════════════════════════════════════════════════════════
#  1. Install Nginx if needed
# ══════════════════════════════════════════════════════════════
if ! command -v nginx &>/dev/null; then
    info "Installing Nginx..."
    apt-get update -qq
    apt-get install -y -qq nginx
    success "Nginx installed."
else
    success "Nginx already installed ($(nginx -v 2>&1 | grep -oP 'nginx/\K.*'))"
fi

# ══════════════════════════════════════════════════════════════
#  2. Write Nginx config
# ══════════════════════════════════════════════════════════════
CONF="/etc/nginx/sites-available/${SERVICE_NAME}"

info "Writing Nginx config → $CONF"
cat > "$CONF" <<NGXEOF
# SnapTravels — Nginx reverse proxy
# Generated by setup_nginx.sh on $(date)

server {
    listen ${NGINX_PORT};
    server_name ${DOMAIN};

    client_max_body_size 20M;

    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # Serve static files directly (bypass Flask)
    location /static/ {
        alias ${APP_DIR}/app/static/;
        expires 30d;
        add_header Cache-Control "public, immutable";
        access_log off;
    }

    # Proxy everything else to Flask
    location / {
        proxy_pass         http://127.0.0.1:${FLASK_PORT};
        proxy_http_version 1.1;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
        proxy_connect_timeout 10s;
    }

    # Health check (no logging)
    location = /health {
        proxy_pass http://127.0.0.1:${FLASK_PORT}/health;
        access_log off;
    }
}
NGXEOF
success "Config written."

# ══════════════════════════════════════════════════════════════
#  3. Enable site and remove default
# ══════════════════════════════════════════════════════════════
ln -sf "$CONF" "/etc/nginx/sites-enabled/${SERVICE_NAME}"
rm -f /etc/nginx/sites-enabled/default
success "Site enabled, default removed."

# ══════════════════════════════════════════════════════════════
#  4. Test and reload
# ══════════════════════════════════════════════════════════════
info "Testing Nginx config..."
nginx -t || err "Nginx config test failed — check $CONF"

info "Restarting Nginx..."
systemctl restart nginx
systemctl enable nginx 2>/dev/null || true
success "Nginx restarted and enabled."

# ══════════════════════════════════════════════════════════════
#  5. Verify
# ══════════════════════════════════════════════════════════════
echo ""
info "Verifying proxy..."
sleep 1

# Check if Flask is running
FLASK_CHECK=$(curl -s --max-time 3 "http://localhost:${FLASK_PORT}/health" 2>/dev/null)
if [ -n "$FLASK_CHECK" ]; then
    success "Flask is running on port $FLASK_PORT"
else
    warn "Flask not running on port $FLASK_PORT — start it with: PORT=$FLASK_PORT bash snaptravels.sh start"
fi

# Check Nginx proxy
NGX_CHECK=$(curl -s --max-time 3 -o /dev/null -w "%{http_code}" "http://localhost:${NGINX_PORT}/" 2>/dev/null)
if [ "$NGX_CHECK" = "200" ] || [ "$NGX_CHECK" = "302" ]; then
    success "Nginx proxy working: localhost:$NGINX_PORT → $NGX_CHECK"
else
    if [ -z "$FLASK_CHECK" ]; then
        warn "Nginx proxy returned $NGX_CHECK — Flask not running yet"
    else
        warn "Nginx proxy returned $NGX_CHECK — check config"
    fi
fi

# ══════════════════════════════════════════════════════════════
#  6. Summary
# ══════════════════════════════════════════════════════════════
echo ""
echo -e "${BOLD}${GREEN}╔═══════════════════════════════════════════════════╗${NC}"
echo -e "${BOLD}${GREEN}║   Nginx Setup Complete!                            ║${NC}"
echo -e "${BOLD}${GREEN}╚═══════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  ${BOLD}Start Flask:${NC}   PORT=$FLASK_PORT bash snaptravels.sh start"
echo ""
if [ "$DOMAIN" != "_" ]; then
    echo -e "  ${BOLD}Access URL:${NC}    http://${DOMAIN}:${NGINX_PORT}"
else
    IP=$(curl -s4 --max-time 3 ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')
    echo -e "  ${BOLD}Access URL:${NC}    http://${IP}:${NGINX_PORT}"
fi
echo ""
echo -e "  ${BOLD}Flow:${NC}          Browser → Nginx :${NGINX_PORT} → Flask :${FLASK_PORT}"
echo ""
echo -e "  ${BOLD}Manage:${NC}"
echo "    systemctl status nginx        # Check Nginx status"
echo "    systemctl restart nginx       # Restart Nginx"
echo "    cat $CONF                     # View config"
echo ""
